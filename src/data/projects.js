// ── Media URL helpers — support both YouTube and Google Drive sources ──
// Drive files must be shared as "Anyone with the link" for thumbnails/embeds to load.
export const thumbUrl = (v) =>
  v.poster
    ? v.poster
    : v.driveId
      ? `https://drive.google.com/thumbnail?id=${v.driveId}&sz=w1000`
      : `https://img.youtube.com/vi/${v.youtubeId}/maxresdefault.jpg`

export const embedUrl = (v, { mute = false, loop = false } = {}) => {
  if (v.driveId) {
    const dp = new URLSearchParams({ autoplay: '1' })
    if (mute) dp.set('mute', '1')
    if (loop) dp.set('loop', '1')
    return `https://drive.google.com/file/d/${v.driveId}/preview?${dp.toString()}`
  }
  const p = new URLSearchParams({
    autoplay: '1',
    rel: '0',
    modestbranding: '1',
    playsinline: '1',
  })
  if (mute) p.set('mute', '1')
  if (loop) { p.set('loop', '1'); p.set('playlist', v.youtubeId); p.set('controls', '1') }
  return `https://www.youtube.com/embed/${v.youtubeId}?${p.toString()}`
}

